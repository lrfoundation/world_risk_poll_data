def finding_ids():
    path = HERE.parents[1] / FOLDER / "published_figures.csv"
    with open(path, encoding="utf-8") as f:
        return [row["finding_id"] for row in csv.DictReader(f)]


IDS = finding_ids()


def by_region(prefix, suffixes):
    """Rows for a chart by region, in the order of the original (the order of the CSV)."""
    keys = []
    for fid in IDS:
        if fid.startswith(prefix):
            key = next((fid[len(prefix):-len(s) - 1] for s in suffixes if fid.endswith("_" + s)), None) if suffixes else fid[len(prefix):]
            if key in REGIONS and key not in keys:
                keys.append(key)
    assert len(keys) == 15, (prefix, keys)
    return [[REGIONS[k], [f"{prefix}{k}_{s}" for s in suffixes] if suffixes else f"{prefix}{k}"] for k in keys]


def groups(prefix, names, suffixes):
    return [[name, [f"{prefix}{key}_{s}" for s in suffixes]] for key, name in names.items()]


def known(rows):
    """Ids the CSV does not hold (segments the original draws without a figure) become null."""
    return [[label, [i if i in IDS else None for i in ids]] for label, ids in rows]


def countries(prefix, names):
    return [[name, f"{prefix}{iso}"] for iso, name in names.items()]


def and_list(items):
    items = [str(i) for i in items]
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


